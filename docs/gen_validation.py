"""Generate the validation report page at docs build time (mkdocs-gen-files)."""

import jax

jax.config.update("jax_enable_x64", True)

import mkdocs_gen_files  # noqa: E402

from qenvs import toolkit  # noqa: E402

out = toolkit.validate()
header = """# Validation report

This page is regenerated by every documentation build (GitHub Actions, CPU, float64)
from `qenvs.toolkit.validate()`, the same function behind `qenvs validate`. Reproduce it
locally with:

```bash
pip install 'qenvs[dev]'    # dev extra adds QuTiP for the cross-checks
qenvs validate --markdown
```

A passing check means the simulation agrees with its reference (closed-form result,
physical constraint, independent solver or QuTiP) within the stated tolerance. It does not
mean the model describes a particular experiment: see each model page for its assumptions
and validity limits.

"""
with mkdocs_gen_files.open("validation.md", "w") as f:
    f.write(header + toolkit.validation_markdown(out))
